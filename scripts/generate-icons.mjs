const missing = Object.entries(MAP).filter(([, f]) => !available.has(f));
if (missing.length) {
  console.error("Missing icon files:", missing);
  process.exit(1);
}

const inner = (file) => {
  const svg = readFileSync(path.join(dir, `${file}.svg`), "utf8").trim();
  const m = svg.match(/<svg[^>]*>([\s\S]*)<\/svg>/);
  return m[1].trim();
};

const lines = [
  "// GENERATED by scripts/generate-icons.mjs from design/icons/*.svg. Do not edit by hand.",
  "// Solid icons (Phosphor Fill). The exported names are the ones the app already used.",
  'import * as React from "react";',
  "",
  "export type IconProps = Omit<React.SVGProps<SVGSVGElement>, \"ref\"> & {",
  "  size?: number | string;",
  "  strokeWidth?: number | string;",
  "  absoluteStrokeWidth?: boolean;",
  "};",
  "export type LucideIcon = React.ForwardRefExoticComponent<IconProps & React.RefAttributes<SVGSVGElement>>;",
  "",
  "function icon(name: string, markup: string): LucideIcon {",
  "  const Icon = React.forwardRef<SVGSVGElement, IconProps>(function Icon(",
  "    { size = 24, strokeWidth: _strokeWidth, absoluteStrokeWidth: _absolute, ...props },",
  "    ref,",
  "  ) {",
  "    return (",
  "      <svg",
  "        ref={ref}",
  '        xmlns="http://www.w3.org/2000/svg"',
  '        viewBox="0 0 256 256"',
  '        fill="currentColor"',
  "        width={size}",
  "        height={size}",
  '        aria-hidden="true"',
  "        {...props}",
  "        dangerouslySetInnerHTML={{ __html: markup }}",
  "      />",
  "    );",
  "  });",
  "  Icon.displayName = name;",
  "  return Icon;",
  "}",
  "",
];
for (const [name, file] of Object.entries(MAP).sort(([a], [b]) => a.localeCompare(b))) {
  lines.push(`export const ${name} = icon(${JSON.stringify(name)}, ${JSON.stringify(inner(file))});`);
}
lines.push("");
writeFileSync(path.join(root, "components/icons.tsx"), lines.join("\n"));
console.log(`wrote components/icons.tsx with ${Object.keys(MAP).length} icons`);
